pub const HERO_GUARD: f32 = 15.0;

pub struct HeroDef {
    pub name: &'static str,
    /// 英霊を共有する文明・民族の代表となる勢力番号
    pub culture: usize,
    /// 国・生没年
    pub era: &'static str,
    /// 兵種（UNIT_DEFS の番号）
    pub ut: u8,
    /// 生贄にした民の能力に対する倍率（1.1〜3.0）
    pub mult: f32,
    pub desc: &'static str,
}

macro_rules! hd {
    ($c:expr, $n:expr, $e:expr, $u:expr, $m:expr, $d:expr) => {
        HeroDef { name: $n, culture: $c, era: $e, ut: $u, mult: $m, desc: $d }
    };
}

